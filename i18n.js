/** Chữ thường, bỏ dấu tiếng Việt, đ -> d. Dùng để so khớp không dấu. */
function fold(s) {
  return String(s || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/đ/gi, "d").toLowerCase();
}

/** Gấp từng ký tự; map[i] là vị trí trong chuỗi gốc của ký tự gấp thứ i (để tô vàng đúng chỗ trên chữ gốc). */
function foldWithMap(s) {
  s = String(s || "");
  let text = "";
  const map = [];
  for (let i = 0; i < s.length; i++) {
    const f = fold(s[i]);
    for (let k = 0; k < f.length; k++) { text += f[k]; map.push(i); }
  }
  return { text, map };
}

/** Số lần needle xuất hiện trong haystack (không chồng lấn). Cả hai đã được gấp. */
function countMatches(haystack, needle) {
  if (!needle) return 0;
  let n = 0, i = 0;
  while ((i = haystack.indexOf(needle, i)) !== -1) { n++; i += needle.length; }
  return n;
}

